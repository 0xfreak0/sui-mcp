#!/usr/bin/env node
/**
 * Regenerate `src/data/guardians-blocklist.json` from the Sui wallet blocklist
 * (github.com/MystenLabs/wallet_blocklist), the list Sui wallets use to hide
 * scam coins, packages and NFT types.
 *
 * It is a third-party, community-maintained list, so the server reports a hit
 * as `flagged_by` with tier `third-party` and never as an address label or a
 * fund-tracing sink.
 *
 * Stored:
 *
 *   - coins: full coin types, package id padded to 64 hex.
 *   - packages: the first 16 hex digits (8 bytes) of each blocklisted package
 *     id. Package ids are hashes, so a collision among ~20k entries has
 *     probability around 1e-11; the saving is about 1 MB.
 *   - object_type_packages: the same prefix for the package that defines each
 *     blocklisted object type. The object list has ~75k types, nearly one per
 *     package, and keeping them whole would add ~7 MB for a lookup that only
 *     needs to know the package.
 *   - allowlists, which win over the blocklists.
 *
 * The domain list is not synced: no tool here takes a URL or a domain.
 *
 *   node scripts/sync-guardians.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "src/data/guardians-blocklist.json");
const REPO = "MystenLabs/wallet_blocklist";
const TIMEOUT_MS = 120_000;
const PREFIX_HEX = 16;

async function json(url) {
  const res = await fetch(url, {
    headers: { "user-agent": "sui-analytics-mcp sync-guardians" },
    signal: AbortSignal.timeout(TIMEOUT_MS),
  });
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  return res.json();
}

function padPackage(pkg) {
  const hex = pkg.trim().toLowerCase().replace(/^0x/, "");
  if (!/^[0-9a-f]{1,64}$/.test(hex)) return null;
  return `0x${hex.padStart(64, "0")}`;
}
const prefix = (pkg) => {
  const p = padPackage(pkg);
  return p ? p.slice(2, 2 + PREFIX_HEX) : null;
};
function normalizeType(t) {
  const [pkg, ...rest] = t.trim().split("::");
  const p = padPackage(pkg ?? "");
  return p && rest.length >= 2 ? `${p}::${rest.join("::")}` : null;
}
const uniqSorted = (xs) => [...new Set(xs.filter(Boolean))].sort();

const head = await json(`https://api.github.com/repos/${REPO}/commits/main`);
const commit = head?.sha;
if (typeof commit !== "string") throw new Error("could not resolve the blocklist's main commit");
const raw = (name) => `https://raw.githubusercontent.com/${REPO}/${commit}/blocklists/${name}`;

const [coinList, packageList, objectList] = await Promise.all(
  ["coin-list.json", "package-list.json", "object-list.json"].map((n) => json(raw(n))),
);

const coins = uniqSorted((coinList.blocklist ?? []).map(normalizeType));
const packages = uniqSorted((packageList.blocklist ?? []).map(prefix));
// A bare id in the object list is a package, not a type; treat it as one.
const objectTypePackages = uniqSorted((objectList.blocklist ?? []).map((t) => prefix(t.split("::")[0])));

if (coins.length === 0 || packages.length === 0) {
  throw new Error("blocklist came back empty; refusing to overwrite the shipped copy");
}

const out = {
  _comment:
    "GENERATED by scripts/sync-guardians.mjs from github.com/MystenLabs/wallet_blocklist; do not edit by hand. Third-party, community-maintained scam lists used by Sui wallets. Reported as flagged_by (tier third-party), never as an address label or a fund-tracing sink. packages and object_type_packages hold the first 16 hex digits of the package id.",
  source_url: `https://github.com/${REPO}`,
  commit,
  retrieved_at: new Date().toISOString().slice(0, 10),
  counts: {
    coins: coins.length,
    packages: packages.length,
    object_types: (objectList.blocklist ?? []).length,
    object_type_packages: objectTypePackages.length,
  },
  prefix_hex_digits: PREFIX_HEX,
  allowlist: {
    coins: uniqSorted((coinList.allowlist ?? []).map(normalizeType)),
    packages: uniqSorted((packageList.allowlist ?? []).map(prefix)),
    object_types: uniqSorted((objectList.allowlist ?? []).map(normalizeType)),
  },
  coins,
  packages,
  object_type_packages: objectTypePackages,
};
writeFileSync(OUT, JSON.stringify(out) + "\n");
console.log(`commit ${commit}: ${coins.length} coins, ${packages.length} packages, ${objectTypePackages.length} object-type packages`);
