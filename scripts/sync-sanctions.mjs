#!/usr/bin/env node
/**
 * Regenerate `src/data/sanctions.json` from OFAC's SDN list: every "Digital
 * Currency Address" OFAC publishes, reduced to the ones this server can match
 * against a chain-qualified account.
 *
 * What is matchable:
 *
 *   - 20-byte hex (0x + 40) under any currency code is an EVM key, so it is
 *     stored under the `eip155` namespace and matches on every EVM chain. OFAC
 *     files the same key as ETH, USDT, USDC, ARB, BSC and so on; the key is the
 *     sanctioned party's on every one of them.
 *   - SOL entries are stored under `solana`.
 *   - A SUI entry, or any 0x + 64 hex listed as SUI, is stored under `sui`.
 *
 * Everything else (XBT, TRX, LTC, XMR, …) is counted and not stored: no tool
 * here produces an account on those chains to match against. Base58 values
 * under USDT/USDC are skipped too, because Tron and Solana addresses share the
 * alphabet and the currency code does not say which chain.
 *
 *   node scripts/sync-sanctions.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseSdnDigitalCurrency } from "./lib/sdn-parse.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "src/data/sanctions.json");
const SOURCE = "https://sanctionslistservice.ofac.treas.gov/api/PublicationPreview/exports/SDN_ENHANCED.XML";
const TIMEOUT_MS = 300_000;

const res = await fetch(SOURCE, { signal: AbortSignal.timeout(TIMEOUT_MS) });
if (!res.ok) throw new Error(`${SOURCE} -> HTTP ${res.status}`);
const xml = await res.text();

const parsed = parseSdnDigitalCurrency(xml);
if (parsed.total === 0) {
  throw new Error("parsed zero digital currency addresses; refusing to write an empty list over a real one");
}

console.log(`OFAC SDN data as of ${parsed.dataAsOf}: ${parsed.total} digital currency addresses`);
console.log(`matchable: ${parsed.accounts.length} (sui ${parsed.suiCount})`);
console.log(`by currency: ${JSON.stringify(parsed.byCurrency)}`);

writeFileSync(
  OUT,
  JSON.stringify(
    {
      _comment:
        "GENERATED by scripts/sync-sanctions.mjs from OFAC's SDN list; do not edit by hand. Only addresses this server can match to a chain-qualified account are stored (EVM keys under eip155, Solana under solana, Sui under sui). by_currency counts every digital currency address OFAC lists, stored or not.",
      source_url: SOURCE,
      list: "OFAC Specially Designated Nationals (SDN) List",
      data_as_of: parsed.dataAsOf,
      retrieved_at: new Date().toISOString().slice(0, 10),
      total_digital_currency_addresses: parsed.total,
      by_currency: parsed.byCurrency,
      sui_address_count: parsed.suiCount,
      accounts: parsed.accounts,
    },
    null,
    1,
  ) + "\n",
);
console.log(`wrote ${OUT}`);
