/**
 * Render the changelog page and the current-release line from CHANGELOG.md and
 * the package version.
 *
 * Pure: no filesystem. `gen-release-pages.mjs` feeds it the repo's CHANGELOG.md
 * and package.json version and writes the result;
 * `test/site-tool-reference.test.ts` compares it with the committed files.
 */

/** Paths are relative to `site/src/content/docs/`. */
export const CHANGELOG_PAGE = "project/changelog.md";
/**
 * "Current release: X.Y.Z", a Markdown partial (the docs loader skips `_`
 * files) that the front page and start/index.mdx import.
 */
export const CURRENT_RELEASE_PARTIAL = "project/_current-release.md";

const REPO = "https://github.com/0xfreak0/sui-mcp";
/** 0.1.0 predates tagged releases; every version from this one has a GitHub release. */
const FIRST_TAGGED = [1, 0, 0];

const GENERATED_BY =
  "Generated by site/scripts/gen-release-pages.mjs from CHANGELOG.md and package.json. " +
  "Do not edit by hand: run `npm run gen:tools` in site/.";

const RELEASE_HEADING = /^## (\d+\.\d+\.\d+) \((\d{4}-\d{2}-\d{2})\)\s*$/;

/**
 * GitHub's anchor for a heading: lower-cased, punctuation other than `-` and
 * `_` dropped, spaces turned into `-`. "1.24.0 (2026-09-29)" -> "1240-2026-09-29".
 */
function githubAnchor(heading) {
  return heading
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, "")
    .replace(/ /g, "-");
}

const semver = (v) => v.split(".").map(Number);
/** Positive when `a` is the later version. */
function compareVersions(a, b) {
  for (let i = 0; i < 3; i++) if (a[i] !== b[i]) return a[i] - b[i];
  return 0;
}

/**
 * Each release in CHANGELOG.md, newest first: version, date, and a summary:
 * the paragraph under the heading when there is one, else the bold lead or
 * first sentence of the entry's first bullet.
 */
export function parseChangelog(text) {
  const lines = text.split("\n");
  const releases = [];
  for (let i = 0; i < lines.length; i++) {
    const m = RELEASE_HEADING.exec(lines[i]);
    if (!m) continue;
    let end = i + 1;
    while (end < lines.length && !lines[end].startsWith("## ")) end++;
    const body = lines.slice(i + 1, end);
    const firstSection = body.findIndex((l) => l.startsWith("### "));
    const intro = (firstSection === -1 ? body : body.slice(0, firstSection)).join("\n").trim();
    let summary = intro.split(/\n\s*\n/)[0]?.replace(/\s*\n\s*/g, " ") ?? "";
    if (!summary) {
      // The first bullet, joined across its wrapped lines: its bold lead, or
      // its first sentence when it has none.
      const start = body.findIndex((l) => l.startsWith("- "));
      let bulletEnd = start + 1;
      while (start !== -1 && bulletEnd < body.length && /^\s+\S/.test(body[bulletEnd])) bulletEnd++;
      const bullet = start === -1 ? "" : body.slice(start, bulletEnd).join(" ").replace(/\s+/g, " ").slice(2);
      summary = /^\*\*(.+?)\*\*/.exec(bullet)?.[1] ?? /^.+?[.!?](?=\s|$)/.exec(bullet)?.[0] ?? bullet;
    }
    if (!summary) throw new Error(`CHANGELOG.md release ${m[1]} has no summary paragraph and no bullet`);
    releases.push({ version: m[1], date: m[2], anchor: githubAnchor(`${m[1]} (${m[2]})`), summary });
  }
  if (releases.length === 0) throw new Error("CHANGELOG.md lists no release headings like `## 1.2.3 (2026-01-31)`");
  return releases.sort((a, b) => compareVersions(semver(b.version), semver(a.version)));
}

function changelogPage(releases, version) {
  const head = [
    "---",
    `# ${GENERATED_BY}`,
    "title: Changelog",
    "description: Every sui-mcp release, newest first, with a summary and links to its full entry and GitHub release.",
    "sidebar:",
    "  order: 3",
    "---",
    "",
  ].join("\n");
  const intro = [
    `The current release is ${version}. Each release below links to its full entry in ` +
      `[CHANGELOG.md](${REPO}/blob/main/CHANGELOG.md), which lists what was added, changed and fixed, ` +
      "and to its GitHub release.",
    "Published versions are on npm as [`sui-analytics-mcp`](https://www.npmjs.com/package/sui-analytics-mcp). " +
      "To check that an installed tarball was built by the project's CI, see " +
      "[Verifying a release](/concepts/security/#verifying-a-release).",
  ];
  const sections = releases.map((r) => {
    const links = [`[Full entry](${REPO}/blob/main/CHANGELOG.md#${r.anchor})`];
    if (compareVersions(semver(r.version), FIRST_TAGGED) >= 0) links.push(`[GitHub release](${REPO}/releases/tag/v${r.version})`);
    return [`## ${r.version} (${r.date})`, r.summary, links.join(" · ")].join("\n\n");
  });
  return `${head}${[...intro, ...sections].join("\n\n")}\n`;
}

function currentReleasePartial(release) {
  return `<!-- ${GENERATED_BY} -->\n\nCurrent release: [${release.version}](/project/changelog/) (${release.date}).\n`;
}

/**
 * Every generated file, keyed by path relative to `site/src/content/docs/`.
 *
 * @param {{ changelog: string, version: string }} input CHANGELOG.md's text and package.json's version
 * @returns {Map<string, string>}
 */
export function renderReleasePages({ changelog, version }) {
  const releases = parseChangelog(changelog);
  const current = releases.find((r) => r.version === version);
  if (!current) throw new Error(`package.json version ${version} has no \`## ${version} (date)\` heading in CHANGELOG.md`);
  return new Map([
    [CHANGELOG_PAGE, changelogPage(releases, version)],
    [CURRENT_RELEASE_PARTIAL, currentReleasePartial(current)],
  ]);
}
